"""Aggregate reports/runs.json + saved predictions into reports/results.md and a GeoJSON of test patches."""
import json, pathlib
import numpy as np
from sklearn.metrics import f1_score
from .data import load, spatial_split
from .geo import to_geojson
from .indices import ndvi, ndwi, ndbi

R = pathlib.Path(__file__).resolve().parents[1] / "reports"


def ms(v):
    return f"{np.mean(v):.4f} ± {np.std(v):.4f}" if len(v) > 1 else f"{v[0]:.4f}"


def main():
    runs = json.loads((R / "runs.json").read_text())
    d = load(); y = d["y"]; split = spatial_split(d["lon"], d["lat"]); te = np.where(split == 2)[0]; cl = list(d["classes"])
    out = ["# Results (generated by sentinel_eurosat.report)\n",
           f"Split by 1x1 degree lon/lat cell: train/val/test = {[int((split == k).sum()) for k in range(3)]}. Test read once per run.\n",
           "## Test performance (mean ± std over seeds)\n", "| variant | seeds | params | accuracy | macro-F1 |", "|---|---|---|---|---|"]
    for v in dict.fromkeys(r["variant"] for r in runs):
        g = [r for r in runs if r["variant"] == v]
        out.append(f"| {v} | {len(g)} | {g[0].get('params', '-')} | {ms([r['test_acc'] for r in g])} | {ms([r['test_macro_f1'] for r in g])} |")
    seeds = sorted({r["seed"] for r in runs if r["variant"] == "ms13"} & {r["seed"] for r in runs if r["variant"] == "rgb"})
    if seeds:
        diff = [next(r["test_macro_f1"] for r in runs if r["variant"] == "ms13" and r["seed"] == s) -
                next(r["test_macro_f1"] for r in runs if r["variant"] == "rgb" and r["seed"] == s) for s in seeds]
        out += [f"\nms13 minus rgb, macro-F1 per seed: {[round(x, 4) for x in diff]} (same seed, same split, same architecture)\n"]
        out += ["## Per-class F1 (mean over seeds)\n", "| class | rgb | ms13 |", "|---|---|---|"]
        f = {v: np.mean([f1_score(y[te], np.load(R / f"pred_{v}_s{s}.npy"), average=None, labels=range(10)) for s in seeds], 0)
             for v in ("rgb", "ms13")}
        out += [f"| {c} | {f['rgb'][k]:.3f} | {f['ms13'][k]:.3f} |" for k, c in enumerate(cl)]
        to_geojson(d, te, y[te], np.load(R / f"pred_ms13_s{seeds[0]}.npy"), R / "test_predictions_ms13.geojson")
    rng = np.random.default_rng(0)
    out += ["\n## Spectral indices by class (mean over 200 random patches per class)\n", "| class | NDVI | NDWI | NDBI |", "|---|---|---|---|"]
    for k, c in enumerate(cl):
        x = d["X"][np.sort(rng.choice(np.where(y == k)[0], 200, replace=False))].astype(np.float32).transpose(1, 0, 2, 3)
        out.append(f"| {c} | {ndvi(x).mean():.2f} | {ndwi(x).mean():.2f} | {ndbi(x).mean():.2f} |")
    (R / "results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
